/** Normalize for matching: strip punctuation, collapse whitespace */
function norm(s: string): string {
  return (s || "").replace(/[."'“”׳״\-_(),:;!?]+/g, " ").replace(/\s+/g, " ").trim();
}

/**
 * Given a control's current tooltip/label, return a richer explanation from
 * the dictionary if the current text is short (a bare label) and a key matches.
 * Returns null when no enrichment applies.
 */
export function enrichTooltip(current: string): string | null {
  const c = norm(current);
  // Only enrich short, label-like tooltips (long ones are already detailed)
  if (c.length > 45) return null;
  let best: { key: string; val: string } | null = null;
  for (const [key, val] of Object.entries(TOOLTIP_DICTIONARY)) {
    if (c.includes(norm(key)) && (!best || key.length > best.key.length)) {
      best = { key, val };
    }
  }
  return best?.val || null;
}
